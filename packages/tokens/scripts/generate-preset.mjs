#!/usr/bin/env node
/**
 * Generates a brand preset from a few inputs (#27).
 *
 *   apui-generate-preset --name forest --primary "#1f6f3d" [options]
 *
 * Options:
 *   --name <name>          Preset name, used as data-preset="<name>" (required)
 *   --primary <hex>        Primary brand color (required)
 *   --secondary <hex>      Secondary color (default: keep the default)
 *   --accent <hex>         Accent color (default: keep the default)
 *   --neutral <mode>       tinted (default) | pure | keep
 *   --font-sans <list>     Comma-separated font families
 *   --font-mono <list>
 *   --font-display <list>
 *   --description <text>
 *   --format <format>      css (default) | dtcg | php | json
 *   --out <path>           File to write (css, php, json; default stdout) or
 *                          directory (dtcg; required)
 *
 * Every generated preset is checked against the WCAG 2.2 AA pairs in every
 * theme. The command exits with an error and writes nothing if any fails.
 */
import { mkdirSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

import { formatFailures } from './lib/contrast-pairs.mjs';
import { phpValue } from './lib/formats.mjs';
import { generatePreset, GeneratorError } from './lib/generator.mjs';
import { formatPresetCss, presetData } from './lib/presets.mjs';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const FORMATS = ['css', 'dtcg', 'php', 'json'];

/** Renders a generated preset in one of the output formats. Returns `{ file: contents }`. */
export function renderPreset(result, format) {
  const { base, model, preset } = result;
  switch (format) {
    case 'css':
      return {
        '': formatPresetCss(base, model, {
          source: 'Generated by apui-generate-preset. Regenerate rather than edit by hand.',
        }),
      };
    case 'json':
      return { '': `${JSON.stringify(presetData(base, model), null, 2)}\n` };
    case 'php':
      return {
        '': `<?php\n\n/**\n * Brand preset "${preset.name}", generated by apui-generate-preset.\n *\n * @package ArtisanPack_UI\n */\n\nreturn ${phpValue(presetData(base, model), 0)};\n`,
      };
    case 'dtcg':
      return Object.fromEntries(
        preset.sources.map((source) => [source.file, `${JSON.stringify(source.tree, null, 2)}\n`]),
      );
    default:
      throw new GeneratorError(`--format must be one of ${FORMATS.join(', ')}`);
  }
}

function main() {
  const { values } = parseArgs({
    options: {
      name: { type: 'string' },
      primary: { type: 'string' },
      secondary: { type: 'string' },
      accent: { type: 'string' },
      neutral: { type: 'string' },
      'font-sans': { type: 'string' },
      'font-mono': { type: 'string' },
      'font-display': { type: 'string' },
      description: { type: 'string' },
      format: { type: 'string', default: 'css' },
      out: { type: 'string' },
      help: { type: 'boolean', short: 'h' },
    },
  });
  if (values.help) {
    console.log(
      'Usage: apui-generate-preset --name <name> --primary <hex> [--format css|dtcg|php|json] [--out <path>]',
    );
    return;
  }
  if (!FORMATS.includes(values.format)) {
    throw new GeneratorError(`--format must be one of ${FORMATS.join(', ')}`);
  }
  if (values.format === 'dtcg' && !values.out) {
    throw new GeneratorError('--format dtcg needs --out <directory>');
  }

  const result = generatePreset(join(packageRoot, 'tokens'), {
    name: values.name,
    primary: values.primary,
    secondary: values.secondary,
    accent: values.accent,
    neutral: values.neutral,
    fontSans: values['font-sans'],
    fontMono: values['font-mono'],
    fontDisplay: values['font-display'],
    description: values.description,
  });
  if (result.failures.length) {
    throw new GeneratorError(
      `The generated preset fails these contrast checks, so nothing was written:\n${formatFailures(result.failures)}`,
    );
  }

  for (const [role, anchor] of Object.entries(result.anchors)) {
    console.error(
      `${role}: ${anchor.ramp} ramp, input ${anchor.exact ? 'placed exactly at' : 'matched to the luminance of'} step ${anchor.step}`,
    );
  }

  const files = renderPreset(result, values.format);
  for (const [file, contents] of Object.entries(files)) {
    if (!values.out) {
      process.stdout.write(contents);
      continue;
    }
    const path = values.format === 'dtcg' ? join(values.out, file) : values.out;
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
    console.error(`wrote ${path}`);
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    if (!(error instanceof GeneratorError)) throw error;
    console.error(error.message);
    process.exitCode = 1;
  }
}
