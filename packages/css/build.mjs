/**
 * Builds the published stylesheets from src/index.css by inlining each
 * @import in order. Package imports (such as @artisanpack-ui/tokens/css)
 * resolve through Node.
 *
 *   dist/index.css     Everything: reset, tokens, presets, components, utilities.
 *   dist/headless.css  The same without the apui.components layer (#25).
 *   dist/tailwind.css  The optional Tailwind v4 preset (#24).
 *   dist/assets.php    The entry points, for the Livewire package (#25, #42).
 */
import { mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { formatTailwind } from './tailwind.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const IMPORT = /^@import\s+['"]([^'"]+)['"];\s*$/gm;

/** The cascade layers, in order (D-002). */
export const LAYERS = ['apui.reset', 'apui.tokens', 'apui.components', 'apui.utilities'];

/** Component stylesheets sit here, and headless mode leaves them out. */
const COMPONENTS = /^\.\/components\//;

function resolveImport(specifier, from) {
  return specifier.startsWith('.') ? resolve(dirname(from), specifier) : require.resolve(specifier);
}

/**
 * Returns the bundled CSS for an entry file. With `headless`, imports from
 * `./components/` are dropped, so the apui.components layer stays empty and
 * everything else (reset, tokens, presets, utilities) is unchanged.
 */
export function bundle(
  entry = join(here, 'src', 'index.css'),
  { headless = false } = {},
  seen = new Set(),
) {
  if (seen.has(entry)) throw new Error(`circular @import of ${entry}`);
  seen.add(entry);
  const css = readFileSync(entry, 'utf8');
  return css.replace(IMPORT, (_line, specifier) =>
    headless && COMPONENTS.test(specifier)
      ? `/* headless: ${specifier} left out */`
      : bundle(resolveImport(specifier, entry), { headless }, new Set(seen)).trimEnd(),
  );
}

/** The entry points, as a PHP array for the Livewire package's published assets. */
export function formatAssetsPhp() {
  return `<?php

/**
 * @artisanpack-ui/css entry points. Generated by packages/css/build.mjs.
 *
 * 'default' is the full stylesheet. 'headless' leaves out the apui.components
 * layer: markup, ARIA and behavior stay the same, only the visual CSS goes.
 *
 * @package ArtisanPack_UI
 */

return [
\t'layers'  => [ ${LAYERS.map((layer) => `'${layer}'`).join(', ')} ],
\t'entries' => [
\t\t'default'  => 'index.css',
\t\t'headless' => 'headless.css',
\t\t'tailwind' => 'tailwind.css',
\t],
];
`;
}

/** Every file in dist/, keyed by name. */
export function buildDist() {
  return {
    'index.css': bundle(),
    'headless.css': bundle(undefined, { headless: true }),
    'tailwind.css': formatTailwind(),
    'assets.php': formatAssetsPhp(),
  };
}

// Real paths, so running the script through a symlink still builds.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dist = join(here, 'dist');
  rmSync(dist, { recursive: true, force: true });
  mkdirSync(dist, { recursive: true });
  for (const [file, contents] of Object.entries(buildDist())) {
    writeFileSync(join(dist, file), contents);
    console.log(`wrote dist/${file}`);
  }
}
