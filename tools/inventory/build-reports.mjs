/**
 * Turns extracted data plus the curated maps into the Phase 0 reports:
 * api-differences.json, parity-matrix.md, api-differences.md, codemod-scope.md.
 */
import { alignComponent, attributeOutcome, STACKS, tally } from './lib/diff.mjs';
import { readJson, writeDoc, writeJson } from './lib/paths.mjs';

const map = readJson( 'component-map.json' ).components;
const aliases = readJson( 'api-aliases.json' );
const extracted = Object.fromEntries( STACKS.map( ( stack ) => [ stack, readJson( `api-${ stack }.json` ) ] ) );
const indexes = Object.fromEntries( STACKS.map( ( stack ) => [ stack, new Map( extracted[ stack ].components.map( ( component ) => [ component.name, component ] ) ) ] ) );
const downstream = readJson( 'downstream-usage.json' ).packages;
const WAVES = [ 'Pilot', 'Form', 'Navigation', 'Layout', 'Feedback', 'Data Display', 'Utility' ];
const snapshot = STACKS.map( ( stack ) => `${ stack } \`${ extracted[ stack ].commit }\`` ).join( ', ' );
const banner = `<!-- Generated by tools/inventory (npm run all). Do not edit by hand. -->\n\n> Snapshot: ${ snapshot }.`;

const sum = ( values ) => values.reduce( ( total, value ) => total + value, 0 );
const count = ( record ) => sum( Object.values( record ?? {} ) );
const code = ( name ) => `\`${ name }\``;
const table = ( headers, rows ) => [
	`| ${ headers.join( ' | ' ) } |`,
	`|${ headers.map( () => '---' ).join( '|' ) }|`,
	...rows.map( ( row ) => `| ${ row.join( ' | ' ) } |` ),
].join( '\n' );
const top = ( record, limit ) => Object.entries( record ).sort( ( a, b ) => b[ 1 ] - a[ 1 ] ).slice( 0, limit );

const aligned = map.map( ( entry ) => alignComponent( entry, indexes, aliases ) );

writeJson( 'api-differences.json', {
	$comment: 'Generated. Seeds @artisanpack-ui/manifest entries and the upgrade rules. `canonical: null` members are removed.',
	snapshot: Object.fromEntries( STACKS.map( ( stack ) => [ stack, extracted[ stack ].commit ] ) ),
	components: aligned.map( ( component, index ) => ( {
		...component,
		structure: map[ index ].structure ?? null,
		rename: map[ index ].rename ?? null,
		consolidation: map[ index ].consolidation ?? null,
	} ) ),
} );

function parityMatrix() {
	const presence = ( names ) => ( names.length ? names.map( code ).join( ' ' ) : '—' );
	const inAll = map.filter( ( entry ) => STACKS.every( ( stack ) => entry[ stack ].length ) );
	const reactVue = map.filter( ( entry ) => ! entry.livewire.length );
	const livewireOnly = map.filter( ( entry ) => entry.livewire.length && ! entry.react.length && ! entry.vue.length );
	const lines = [
		'# Component parity matrix',
		'',
		banner,
		'',
		`${ map.length } canonical components come from ${ sum( STACKS.map( ( stack ) => extracted[ stack ].components.length ) ) } exports: ${ STACKS.map( ( stack ) => `${ extracted[ stack ].components.length } ${ stack }` ).join( ', ' ) }.`,
		'',
		table( [ 'Where it exists', 'Components' ], [
			[ 'All three stacks', inAll.length ],
			[ 'Livewire only', livewireOnly.length ],
			[ 'React and Vue only', reactVue.length ],
		] ),
		'',
		'React and Vue match each other almost everywhere; the only exports that differ are `File`/`FileUpload` and React-only `StatGroup`. The real gap is Livewire against the other two.',
		'',
		'`canonical` names come from the accepted [vocabulary](vocabulary.md). A row existing in all three stacks does not mean equal capability: see the notes, and [api-differences.md](api-differences.md).',
		'',
	];

	for ( const wave of WAVES ) {
		const rows = map.filter( ( entry ) => entry.wave === wave );

		lines.push( `## ${ wave }`, '' );
		lines.push( table(
			[ 'Canonical', 'Issue', 'Livewire', 'React', 'Vue', 'Notes' ],
			rows.map( ( entry ) => [
				`**${ entry.canonical }**`,
				entry.issue ? `#${ entry.issue }` : '**none**',
				presence( entry.livewire ),
				presence( entry.react ),
				presence( entry.vue ),
				[ entry.rename, entry.structure, entry.note ].filter( Boolean ).join( ' ' ),
			] ),
		), '' );
	}

	lines.push(
		'## Launch exceptions',
		'',
		'Every component ships in all three stacks at launch except these ([D-003](../decisions.md#d-003-full-parity-at-launch-with-four-exceptions)).',
		'',
		table( [ 'Component', 'At launch' ], map.filter( ( entry ) => entry.launchException ).map( ( entry ) => [ `**${ entry.canonical }**`, entry.launchException ] ) ),
		'',
		`The other Livewire-only components need React and Vue ports, unless a consolidation below absorbs them: ${ livewireOnly.filter( ( entry ) => ! entry.launchException ).map( ( entry ) => entry.canonical ).join( ', ' ) }.`,
		'',
		'## Consolidation candidates',
		'',
		table( [ 'Component', 'Proposal' ], map.filter( ( entry ) => entry.consolidation ).map( ( entry ) => [ `**${ entry.canonical }**`, entry.consolidation ] ) ),
		'',
		'## Components missing from the wave issues',
		'',
		'These exist in React and Vue but are not listed in any wave issue, which only names Livewire components. They should be added so they are not dropped.',
		'',
		table( [ 'Component', 'Proposed wave' ], map.filter( ( entry ) => ! entry.issue ).map( ( entry ) => [ `**${ entry.canonical }**`, entry.wave ] ) ),
	);

	writeDoc( 'parity-matrix.md', lines.join( '\n' ) );

	return { inAll: inAll.length, livewireOnly: livewireOnly.length, reactVue: reactVue.length };
}

function enumValues( prop ) {
	const seen = {};

	for ( const stack of STACKS ) {
		seen[ stack ] = new Set();

		for ( const component of extracted[ stack ].components ) {
			const member = component.props.find( ( item ) => item.name === prop );

			member?.values?.forEach( ( value ) => seen[ stack ].add( value ) );
		}
	}

	return STACKS.map( ( stack ) => [ ...seen[ stack ] ].join( ' · ' ) || '—' );
}

function apiDifferences() {
	const all = tally( aligned.flatMap( ( component ) => component.members ) );
	const worst = [ ...aligned ]
		.filter( ( component ) => component.stacks.length > 1 )
		.sort( ( a, b ) => ( b.totals.rename + b.totals.missing + b.totals.behavioral + b.totals.remove ) - ( a.totals.rename + a.totals.missing + a.totals.behavioral + a.totals.remove ) )
		.slice( 0, 12 );
	const pilot = aligned.filter( ( component ) => 'Pilot' === component.wave );
	const memberRow = ( member ) => {
		const name = member.canonical ?? '*(removed)*';
		const notes = member.differences.map( ( difference ) => {
			if ( 'rename' === difference.kind ) {
				return `${ difference.stack }: rename ${ code( difference.from ) }${ difference.note ? ` (${ difference.note })` : '' }`;
			}

			if ( 'remove' === difference.kind ) {
				return `${ difference.stack }: remove ${ code( difference.from ) }${ difference.note ? ` (${ difference.note })` : '' }`;
			}

			return 'missing' === difference.kind ? `${ difference.stack }: missing` : `${ difference.aspect } differs (${ difference.detail })`;
		} );

		return [ code( name ), ...STACKS.map( ( stack ) => ( member.current[ stack ] ? code( member.current[ stack ].name ) : '—' ) ), notes.join( '; ' ).replaceAll( '|', '\\|' ) ];
	};
	const lines = [
		'# API differences',
		'',
		banner,
		'',
		'Summary of [data/api-differences.json](data/api-differences.json), the machine-readable catalogue. Each member records today\'s name, type, default and values per stack, plus its differences, so it can seed manifest entries and drive the upgrade rules.',
		'',
		table( [ 'Members', 'rename', 'missing', 'behavioral', 'remove', 'DaisyUI-coupled' ], [ [ all.members, all.rename, all.missing, all.behavioral, all.remove, all.daisyCoupled ] ] ),
		'',
		'- **rename:** same concept, different name today or under the proposed vocabulary.',
		'- **missing:** present in another stack but not this one. HTML attributes that pass through (`disabled`, `name`, …) are not counted.',
		'- **behavioral:** same name, but the form (prop vs slot), type, allowed values or default differ.',
		'- **remove:** dropped under the vocabulary.',
		'- Not counted as missing: `classes.*` and `aria-label` (every component gets them), members Livewire binds with `wire:model`, and Livewire-only conveniences such as `errorField`.',
		'- Renames depend on [data/api-aliases.json](data/api-aliases.json). A concept with no alias yet shows as **missing** in each stack rather than as a rename, so `missing` is an upper bound until each component\'s spec is written.',
		'',
		'## Shared enums today',
		'',
		table( [ 'Prop', 'Livewire', 'React', 'Vue' ], [ 'size', 'color', 'variant', 'tooltipPosition' ].map( ( prop ) => [ code( prop ), ...enumValues( prop ) ] ) ),
		'',
		'Livewire values come from docblocks and are only captured where they are listed. `color` and `variant` are open strings in most Livewire components, so that column is incomplete by nature.',
		'',
		'## By wave',
		'',
		table( [ 'Wave', 'Components', 'Members', 'rename', 'missing', 'behavioral', 'remove' ], WAVES.map( ( wave ) => {
			const group = aligned.filter( ( component ) => component.wave === wave );
			const totals = tally( group.flatMap( ( component ) => component.members ) );

			return [ wave, group.length, totals.members, totals.rename, totals.missing, totals.behavioral, totals.remove ];
		} ) ),
		'',
		'## Largest gaps',
		'',
		table( [ 'Component', 'Members', 'rename', 'missing', 'behavioral', 'remove' ], worst.map( ( { canonical, totals } ) => [ canonical, totals.members, totals.rename, totals.missing, totals.behavioral, totals.remove ] ) ),
		'',
		'## Pilot components',
		'',
	];

	for ( const component of pilot ) {
		lines.push( `### ${ component.canonical }`, '', table( [ 'Canonical', 'Livewire', 'React', 'Vue', 'Differences' ], component.members.filter( ( member ) => member.differences.length ).map( memberRow ) ), '' );
	}

	writeDoc( 'api-differences.md', lines.join( '\n' ) );

	return all;
}

function codemodScope() {
	const canonicalBy = Object.fromEntries( STACKS.map( ( stack ) => [ stack, new Map( map.flatMap( ( entry ) => entry[ stack ].map( ( name ) => [ name, entry ] ) ) ) ] ) );
	const kebab = ( name ) => name.replace( /([a-z0-9])([A-Z])/g, '$1-$2' ).toLowerCase();

	const impact = ( usage, stack ) => {
		const result = { usages: 0, renamedComponents: 0, attributes: 0, renamedAttributes: 0, removedAttributes: 0, byComponent: {}, byAttribute: {} };

		for ( const [ name, { count: uses, attributes } ] of Object.entries( usage ) ) {
			const entry = canonicalBy[ stack ].get( name );

			result.usages += uses;

			if ( entry ) {
				const target = 'livewire' === stack ? kebab( entry.canonical ) : entry.canonical;

				// Children of compositional families (menu-item, tab) keep their names.
				const primary = name === entry[ stack ][ 0 ] || entry.consolidation;
				const renamed = target !== name && primary && ! entry.structure && ! entry.keepNames?.includes( name );

				if ( renamed ) {
					result.renamedComponents += uses;
					result.byComponent[ `${ name } → ${ target }` ] = uses;
				}

				for ( const [ attribute, times ] of Object.entries( attributes ) ) {
					const outcome = attributeOutcome( aliases, entry.canonical, stack, attribute );

					result.attributes += times;

					if ( 'unchanged' !== outcome ) {
						result[ 'rename' === outcome ? 'renamedAttributes' : 'removedAttributes' ] += times;
						result.byAttribute[ `${ attribute } (${ outcome })` ] = ( result.byAttribute[ `${ attribute } (${ outcome })` ] ?? 0 ) + times;
					}
				}
			}
		}

		return result;
	};

	const rows = downstream.map( ( item ) => ( {
		...item,
		bladeImpact: impact( item.blade, 'livewire' ),
		reactImpact: impact( item.react, 'react' ),
		vueImpact: impact( item.vue, 'vue' ),
		classes: Object.fromEntries( [ 'component', 'themeBase', 'themeContent', 'themeSemantic', 'ambiguous' ].map( ( kind ) => [ kind, count( item.daisyClasses[ kind ] ) ] ) ),
	} ) ).filter( ( item ) => item.bladeImpact.usages || item.reactImpact.usages || item.vueImpact.usages || item.daisyFiles || count( item.themeVariables ) || count( item.config ) );

	const planned = new Set( [ 'ecommerce-admin-livewire', 'forms', 'analytics', 'livewire-starter-kit', 'media-library', 'seo', 'pagespeed-insights', 'ai', 'security', 'react-starter-kit', 'vue-starter-kit' ] );
	const merged = ( pick ) => {
		const totals = {};

		for ( const row of rows ) {
			for ( const stack of [ 'bladeImpact', 'reactImpact', 'vueImpact' ] ) {
				for ( const [ key, value ] of Object.entries( row[ stack ][ pick ] ) ) {
					totals[ key ] = ( totals[ key ] ?? 0 ) + value;
				}
			}
		}

		return totals;
	};
	const mergedClasses = ( kind ) => {
		const totals = {};

		for ( const row of rows ) {
			for ( const [ key, value ] of Object.entries( row.daisyClasses[ kind ] ?? {} ) ) {
				totals[ key ] = ( totals[ key ] ?? 0 ) + value;
			}
		}

		return totals;
	};
	const totalOf = ( pick ) => sum( rows.map( pick ) );
	const uses = ( row ) => row.bladeImpact.usages + row.reactImpact.usages + row.vueImpact.usages;
	const ordered = [ ...rows ].sort( ( a, b ) => ( uses( b ) + b.classes.component ) - ( uses( a ) + a.classes.component ) );
	const unplanned = ordered.filter( ( row ) => ! planned.has( row.name ) );
	const lines = [
		'# Codemod scope',
		'',
		banner,
		'',
		'Sizes the migration for Phase 6 (tooling) and Phase 7 (dogfood). Scans every package beside this repo, excluding `tests`, `docs`, `vendor`, `node_modules` and build output, and the three component libraries themselves. Per-package data is in [data/downstream-usage.json](data/downstream-usage.json).',
		'',
		'**Rename counts follow the [vocabulary](vocabulary.md)**, so they move if it changes. The DaisyUI counts do not.',
		'',
		'## Totals',
		'',
		table( [ 'Measure', 'Count' ], [
			[ 'Packages touching the UI layer', rows.length ],
			[ 'Blade files using library components', totalOf( ( row ) => row.bladeFiles ) ],
			[ 'Blade component usages', totalOf( ( row ) => row.bladeImpact.usages ) ],
			[ 'React component usages', totalOf( ( row ) => row.reactImpact.usages ) ],
			[ 'Vue component usages', totalOf( ( row ) => row.vueImpact.usages ) ],
			[ 'Usages of a renamed component', totalOf( ( row ) => row.bladeImpact.renamedComponents + row.reactImpact.renamedComponents + row.vueImpact.renamedComponents ) ],
			[ 'Attributes needing a rename', totalOf( ( row ) => row.bladeImpact.renamedAttributes + row.reactImpact.renamedAttributes + row.vueImpact.renamedAttributes ) ],
			[ 'Attributes that are removed (glass tints, `uuid`, … have no downstream use)', totalOf( ( row ) => row.bladeImpact.removedAttributes + row.reactImpact.removedAttributes + row.vueImpact.removedAttributes ) ],
			[ 'Raw DaisyUI component classes', totalOf( ( row ) => row.classes.component ) ],
			[ 'Ambiguous DaisyUI-named classes', totalOf( ( row ) => row.classes.ambiguous ) ],
			[ 'DaisyUI-only theme utilities (`bg-base-*`, `*-content`)', totalOf( ( row ) => row.classes.themeBase + row.classes.themeContent ) ],
			[ 'Semantic color utilities (`bg-primary`, …)', totalOf( ( row ) => row.classes.themeSemantic ) ],
			[ 'DaisyUI theme variable references', totalOf( ( row ) => count( row.themeVariables ) ) ],
		] ),
		'',
		'## By package',
		'',
		'Sorted by component usages plus raw classes, which suggests a dogfood order. "Attr." is attributes renamed + removed. "Ref" is what was scanned: the checked-out branch, or `origin/main` when that holds more UI. Several counts come from unmerged branches, so expect them to move: `forms` and `ecommerce-storefront-livewire` carry far more UI on their branches than on `main`.',
		'',
		table(
			[ 'Package', 'Ref', 'In plan', 'Blade files', 'Blade uses', 'React uses', 'Vue uses', 'Attr.', 'DaisyUI files', 'Component classes', 'Theme utilities', 'Theme vars', 'Depends on daisyui' ],
			ordered.map( ( row ) => [
				row.name,
				code( row.ref ),
				planned.has( row.name ) ? 'yes' : '**no**',
				row.bladeFiles,
				row.bladeImpact.usages,
				row.reactImpact.usages,
				row.vueImpact.usages,
				sum( [ row.bladeImpact, row.reactImpact, row.vueImpact ].map( ( item ) => item.renamedAttributes + item.removedAttributes ) ),
				row.daisyFiles,
				row.classes.component,
				row.classes.themeBase + row.classes.themeContent,
				count( row.themeVariables ),
				row.dependsOn.includes( 'daisyui' ) ? 'yes' : '—',
			] ),
		),
		'',
		'## Scope the plan does not list',
		'',
		`The plan's consumer table has 9 Blade packages plus the starter kits. These ${ unplanned.length } also touch the UI layer:`,
		'',
		table( [ 'Package', 'Why it matters' ], unplanned.map( ( row ) => [
			row.name,
			[
				uses( row ) ? `${ uses( row ) } component usages` : null,
				row.classes.component ? `${ row.classes.component } raw DaisyUI classes` : null,
				count( row.themeVariables ) ? `${ count( row.themeVariables ) } theme variable references` : null,
			].filter( Boolean ).join( ', ' ) || 'configuration only',
		] ) ),
		'',
		`Planned packages that also ship React or Vue UIs, which Phase 7 treats as Blade-only: ${ ordered.filter( ( row ) => planned.has( row.name ) && ! row.name.endsWith( 'starter-kit' ) && row.reactImpact.usages + row.vueImpact.usages ).map( ( row ) => row.name ).join( ', ' ) }.`,
		'',
		`Planned packages with no UI usage at this snapshot: ${ [ ...planned ].filter( ( name ) => ! rows.some( ( row ) => row.name === name ) ).join( ', ' ) || 'none' }.`,
		'',
		'## What the codemod can rewrite',
		'',
		'### Component renames',
		'',
		table( [ 'Rename', 'Usages' ], top( merged( 'byComponent' ), 25 ).map( ( [ name, value ] ) => [ code( name ), value ] ) ),
		'',
		'### Attribute changes',
		'',
		table( [ 'Attribute', 'Usages' ], top( merged( 'byAttribute' ), 30 ).map( ( [ name, value ] ) => [ code( name ), value ] ) ),
		'',
		'`variant` on Button is the largest single rule and cannot be a blind rename: `variant="primary"` must become `color`, while `variant="ghost"` stays `variant`. The rule has to inspect the value. `horizontal` and `inline` also rewrite to an `orientation` value rather than a new name.',
		'',
		'## What needs a report, not a rewrite',
		'',
		'### Raw DaisyUI component classes',
		'',
		table( [ 'Class', 'Uses' ], top( mergedClasses( 'component' ), 30 ).map( ( [ name, value ] ) => [ code( name ), value ] ) ),
		'',
		'### Ambiguous classes',
		'',
		'These names are also plain Tailwind utilities or common custom hooks, so the upgrade command should warn and never rewrite.',
		'',
		table( [ 'Class', 'Uses' ], top( mergedClasses( 'ambiguous' ), 15 ).map( ( [ name, value ] ) => [ code( name ), value ] ) ),
		'',
		'### DaisyUI-only theme utilities',
		'',
		'`bg-base-*` and `*-content` have no token equivalent yet. Foundations must decide what the Tailwind preset exposes, or this usage has nowhere to go. Semantic utilities such as `bg-primary` survive through the preset and are low risk.',
		'',
		table( [ 'Utility', 'Uses' ], top( { ...mergedClasses( 'themeBase' ), ...mergedClasses( 'themeContent' ) }, 15 ).map( ( [ name, value ] ) => [ code( name ), value ] ) ),
		'',
		'### Theme variables and configuration',
		'',
		table( [ 'Package', 'Variables', 'Config references' ], rows.filter( ( row ) => count( row.themeVariables ) || count( row.config ) ).map( ( row ) => [
			row.name,
			top( row.themeVariables, 4 ).map( ( [ name, value ] ) => `${ code( name ) } ×${ value }` ).join( ', ' ) || '—',
			top( row.config, 3 ).map( ( [ name, value ] ) => `${ code( name ).replaceAll( '|', '\\|' ) } ×${ value }` ).join( ', ' ) || '—',
		] ) ),
		'',
		'`--color-*` names are also used by non-DaisyUI code, so review these by hand. The no-shim decision means each one must be repointed.',
		'',
		'## Package-owned tags',
		'',
		`Excluded from the counts above: ${ sum( rows.map( ( row ) => count( row.packageOwnedTags ) ) ) } usages of tags such as \`x-artisanpack-ec-*\`, which packages register themselves under the same prefix. Their own views are scanned, so their DaisyUI classes are counted. \`artisanpack:upgrade-ui\` must leave these tags alone.`,
	];

	writeDoc( 'codemod-scope.md', lines.join( '\n' ) );
}

const parity = parityMatrix();
const diffs = apiDifferences();

codemodScope();
console.log( parity, diffs );
